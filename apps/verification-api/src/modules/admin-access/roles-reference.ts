import { PERMISSIONS, SYSTEM_ROLES, type PermissionScope } from "./admin-permissions";

/**
 * The roles and permissions section of docs/AUTH.md, built from the code so the doc never drifts.
 * `npm run docs:roles` rewrites it; a unit test fails when the doc is stale.
 */
export const ROLES_START = "<!-- roles:start (generated by npm run docs:roles; do not edit by hand) -->";
export const ROLES_END = "<!-- roles:end -->";

const TITLES: Record<PermissionScope, string> = {
  GLOBAL: "Keystone platform permissions",
  PARTNER: "Partner permissions (one partner, or every partner for Keystone roles)",
  VENDOR: "Vendor permissions (one vendor, or every vendor for Keystone roles)"
};

const cell = (text: string) => text.replace(/\|/g, "\\|");

export function rolesReferenceMarkdown(): string {
  const lines: string[] = [];
  lines.push("### Roles", "");
  lines.push("| Role | Key | Granted at | For |", "|---|---|---|---|");
  for (const role of SYSTEM_ROLES) lines.push(`| ${role.name} | \`${role.key}\` | ${role.scope} | ${cell(role.description)} |`);

  for (const scope of ["GLOBAL", "PARTNER", "VENDOR"] as PermissionScope[]) {
    const permissions = PERMISSIONS.filter((permission) => permission.scope === scope);
    // Columns: every role that holds at least one permission of this scope.
    const roles = SYSTEM_ROLES.filter((role) => permissions.some((permission) => (role.permissions as readonly string[]).includes(permission.key)));
    lines.push("", `### ${TITLES[scope]}`, "");
    lines.push(`| Permission | What it allows | ${roles.map((role) => role.name).join(" | ")} |`);
    lines.push(`|---|---|${roles.map(() => ":-:").join("|")}|`);
    for (const permission of permissions) {
      const marks = roles.map((role) => ((role.permissions as readonly string[]).includes(permission.key) ? "✓" : ""));
      lines.push(`| \`${permission.key}\` | ${cell(permission.description)} | ${marks.join(" | ")} |`);
    }
  }
  return [ROLES_START, "", ...lines, "", ROLES_END].join("\n");
}

/** The doc with its generated section replaced. */
export function withRolesReference(doc: string): string {
  const start = doc.indexOf(ROLES_START);
  const end = doc.indexOf(ROLES_END);
  if (start < 0 || end < start) throw new Error("docs/AUTH.md has no roles markers");
  return doc.slice(0, start) + rolesReferenceMarkdown() + doc.slice(end + ROLES_END.length);
}
